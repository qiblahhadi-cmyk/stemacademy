import test from "node:test";
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const publicRoot = path.join(projectRoot, "public");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(fullPath));
    else files.push(fullPath);
  }
  return files;
}

function publicPath(reference) {
  return path.join(publicRoot, reference.replace(/^\/+/, "").split(/[?#]/)[0]);
}

// Bundles under assets/js/bundles/ are generated by `npm run build:client` from
// src/client. Their IDs and existence are checked against those sources.
const BUNDLE_PREFIX = "/assets/js/bundles/";
// Must match the entry points in scripts/build-client.mjs.
const BUNDLE_SOURCES = { "login.js": "login.js", "session.js": "session-entry.js" };
function sourceForBundle(reference) {
  const name = BUNDLE_SOURCES[reference.slice(BUNDLE_PREFIX.length)];
  if (!name) return path.join(projectRoot, "src", "client", "__unknown_bundle__.js");
  return path.join(projectRoot, "src", "client", name);
}
function sourceFileExists(reference) {
  return reference.startsWith(BUNDLE_PREFIX)
    ? existsSync(sourceForBundle(reference))
    : publicFiles.includes(publicPath(reference));
}

const publicFiles = await walk(publicRoot);
const htmlFiles = publicFiles.filter(file => file.endsWith(".html"));
const jsFiles = publicFiles.filter(file => file.endsWith(".js"));

test("Every page loads existing local scripts and stylesheets", async () => {
  assert.ok(htmlFiles.length > 0, "Expected at least one HTML page");
  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    const references = [
      ...[...html.matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["']/gi)].map(match => match[1]),
      ...[...html.matchAll(/<link\b[^>]*\bhref=["']([^"']+\.css)(?:[?#][^"']*)?["']/gi)].map(match => match[1])
    ];
    for (const reference of references.filter(value => value.startsWith("/"))) {
      assert.ok(
        sourceFileExists(reference),
        `${path.relative(publicRoot, file)} references missing asset ${reference}`
      );
    }
  }
});

test("Page navigation links point to existing local HTML pages", async () => {
  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    const links = [...html.matchAll(/\bhref=["'](\/[^"'#?]+\.html)(?:[?#][^"']*)?["']/gi)];
    for (const match of links) {
      assert.ok(
        publicFiles.includes(publicPath(match[1])),
        `${path.relative(publicRoot, file)} links to missing page ${match[1]}`
      );
    }
  }
});

test("JavaScript files pass Node syntax checks", () => {
  assert.ok(jsFiles.length > 0, "Expected frontend JavaScript files");
  for (const file of jsFiles) {
    const result = spawnSync(process.execPath, ["--check", file], { encoding: "utf8" });
    assert.equal(
      result.status,
      0,
      `${path.relative(publicRoot, file)} has a syntax error:\n${result.stderr || result.stdout}`
    );
  }
});

test("HTML pages have unique IDs and linked scripts use existing IDs", async () => {
  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    const ids = [...html.matchAll(/\bid=["']([^"']+)["']/gi)].map(match => match[1]);
    assert.equal(
      new Set(ids).size,
      ids.length,
      `${path.relative(publicRoot, file)} contains duplicate HTML IDs`
    );

    const linkedScripts = [...html.matchAll(/<script\b[^>]*\bsrc=["'](\/[^"']+\.js)(?:[?#][^"']*)?["']/gi)];
    for (const match of linkedScripts) {
      const scriptPath = match[1].startsWith(BUNDLE_PREFIX)
        ? sourceForBundle(match[1])
        : publicPath(match[1]);
      const script = await readFile(scriptPath, "utf8");
      const referencedIds = [...script.matchAll(/getElementById\(["']([^"']+)["']\)/g)]
        .map(reference => reference[1]);
      for (const id of referencedIds) {
        assert.ok(
          ids.includes(id),
          `${path.relative(publicRoot, file)} loads ${match[1]} which requests missing ID #${id}`
        );
      }
    }
  }
});

import { PAGE_POLICY, navTargetFor } from "../../src/client/nav-policy.js";

// Pages reachable without a session: sign-in and the access-denied page.
const UNPROTECTED_PAGES = ["login.html", "forbidden.html"];

test("No page uses fragment-only navigation links that cannot leave the page", async () => {
  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    const fragmentLinks = [...html.matchAll(/\bhref=["'](\/?#[^"']*)["']/gi)].map(match => match[1]);
    assert.deepEqual(
      fragmentLinks,
      [],
      `${path.relative(publicRoot, file)} has fragment-only navigation links`
    );
  }
});

test("Every local page link targets an existing page with a role policy", async () => {
  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    const targets = [...html.matchAll(/\bhref=["'](\/[^"'#?]*)(?:[?#][^"']*)?["']/gi)].map(match => match[1]);
    for (const target of targets) {
      if (target.startsWith("/assets/") || target.startsWith("/api/") || target === "/manifest.json") continue;
      const pageName = target === "/" ? "index.html" : target.replace(/^\/+/, "");
      if (!pageName.endsWith(".html")) continue;
      assert.ok(
        publicFiles.includes(publicPath(pageName)),
        `${path.relative(publicRoot, file)} links to missing page ${target}`
      );
      if (UNPROTECTED_PAGES.includes(pageName)) continue;
      assert.ok(
        PAGE_POLICY[pageName],
        `${path.relative(publicRoot, file)} links to ${target}, which has no role policy`
      );
    }
  }
});

test("Every role resolves each sidebar destination to a page it may open or hides the link", async () => {
  const roles = ["admin", "teacher", "student"];
  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    const navHtml = [...html.matchAll(/<a\b[^>]*\bclass=["'][^"']*\bnav-link\b[^"']*["'][^>]*>/gi)].map(match => match[0]);
    for (const anchor of navHtml) {
      const href = anchor.match(/\bhref=["']([^"']+)["']/i)?.[1];
      if (!href || !href.endsWith(".html") && href !== "/") continue;
      const original = href === "/" ? "index.html" : href.replace(/^\/+/, "");
      if (UNPROTECTED_PAGES.includes(original)) continue;
      for (const role of roles) {
        const target = navTargetFor(role, original);
        assert.ok(
          PAGE_POLICY[target] !== undefined,
          `${path.relative(publicRoot, file)} sends ${role} to ${target}, which has no policy`
        );
      }
    }
  }
});

test("Course Hub is not linked from any page in the sidebar", async () => {
  for (const file of htmlFiles) {
    const html = await readFile(file, "utf8");
    assert.doesNotMatch(
      html,
      /<a\b[^>]*\bhref=["']\/?course-hub\.html/i,
      `${path.relative(publicRoot, file)} links to the owner-hidden Course Hub`
    );
  }
});
